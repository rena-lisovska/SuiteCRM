#!/usr/bin/env bash
set -e

MODEL="qwen3:4b"

CODE="$(cat)"
if [ -z "$CODE" ]; then
  echo "No code selected"
  exit 0
fi

PROMPT=$(cat <<EOF
Роль: ты — опытный Java-разработчик и QA Automation Engineer. Твоя задача — провести Code Review предоставленного кода
и выявить реальные проблемы, которые могут повлиять на корректность, надёжность, безопасность и сопровождаемость.

Проверь следующие аспекты:
1. Корректность: ошибки синтаксиса и логики, неверные условия, обработка null, граничные случаи.
2. Баги: ситуации, в которых код может работать неправильно или нестабильно.
3. Безопасность: потенциальные уязвимости и небезопасная обработка данных, если применимо.
4. Качество Java-кода: читаемость, именование, дублирование, неиспользуемый код, соответствие общепринятым практикам.
5. Если это автотест: корректность assertions, достаточность проверок, независимость теста, качество тестовых данных, риск flaky test, корректность setup и cleanup, если они видны в предоставленном коде.

Правила ревью:
- Сообщай только о проблемах, которые можно обосновать предоставленным кодом.
- Не считай отсутствие контекста доказательством ошибки. Если для вывода не хватает информации, явно укажи это.
- Не предлагай изменения только ради стиля, если они не улучшают код существенно.
- Не переписывай весь код без необходимости.
- Если серьёзных проблем не найдено, сообщи об этом и укажи ограничения анализа.

Формат ответа:
1. Краткий итог: оценка состояния кода в 1–3 предложениях.
2. Найденные проблемы — для каждой укажи:
   - Приоритет: Critical / High / Medium / Low.
   - Место проблемы.
   - Что не так и почему.
   - Возможные последствия.
   - Конкретный способ исправления, при необходимости с коротким примером кода.
3. Рекомендации по улучшению — только если они действительно полезны.
4. Что нельзя проверить без дополнительного контекста.

Отвечай на русском языке. Будь конкретным, не повторяй одно замечание разными словами.

CODE:
$CODE
EOF
)

echo "===== AI REVIEW (LOCAL) ====="
echo "$PROMPT" | ollama run "$MODEL"
echo "============================="